-- Return:

-- City
-- Guest_ID
-- Guest_Name
-- Reservation_ID
-- Bill_Amount

SELECT *
FROM (
	SELECT *,
		   ROW_NUMBER() OVER(PARTITION BY City
           ORDER BY Bill_Amount DESC) AS Row_Num
	FROM (
		SELECT G.City, G.Guest_ID, G.Guest_Name, R.Reservation_ID, R.Bill_Amount
        FROM Guests G
		INNER JOIN Reservations R
			ON G.Guest_ID = R.Guest_ID
	)C
)H
WHERE Row_Num = 1;
		   