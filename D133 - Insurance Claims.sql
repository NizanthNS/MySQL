    Claim_ID INT PRIMARY KEY,
    Policyholder_ID INT,
    Claim_Type VARCHAR(50),
    Claim_Date DATE,
    Claim_Amount DECIMAL(10,2),
    FOREIGN KEY (Policyholder_ID)
        REFERENCES Policyholders(Policyholder_ID)
);

